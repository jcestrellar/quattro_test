/* PARAMETER ID */

function GM2_PID(GID, VID, PART, KEY) {
	return (((GID  << 24) & 0xff000000) |
			((VID  << 16) & 0x00ff0000) |
			((PART <<  8) & 0x0000ff00) |
			((KEY       ) & 0x000000ff))
}

